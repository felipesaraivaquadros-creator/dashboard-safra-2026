  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[a]);
  const hash='a'.repeat(64), storagePath=a+'/'+hash+'.pdf';
  await db.query("INSERT INTO public.despesas_documentos(hash,nome,storage_path) VALUES($1,'teste.pdf',$2)",[hash,storagePath]);
  const row={id:hash+':1:2',documentId:hash,page:1,line:2,raw:'02/09/2026 PAGAMENTO 10,00 D',date:'2026-09-02',description:'Pagamento',beneficiary:'Agro',cents:1000,direction:'debito',decision:'incluir',reason:'Conferido',refundOf:'',reviewed:true};
